// Умный поиск статей: формы слов + разговорные синонимы. Без интернета.
(function () {
  // грубый стеммер: отрезаем типичные окончания русских слов
  const ENDINGS = /(ями|ами|ого|ему|ому|ыми|ими|ией|иях|иям|ием|ах|ях|ам|ям|ов|ев|ей|ой|ий|ый|ая|яя|ое|ее|ие|ые|ую|юю|ом|ем|ым|им|ть|ти|ла|ло|ли|ал|ил|ел|ул|ет|ит|ут|ют|ат|ят|ешь|ишь|ся|сь|а|я|о|е|ы|и|у|ю|ь|й)$/;
  const norm = (s) => String(s || "").toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9.\s]/g, " ");
  const stem = (w) => {
    if (w.length <= 4 || /^\d/.test(w)) return w;
    let s = w;
    for (let i = 0; i < 2 && s.length > 4; i += 1) s = s.replace(ENDINGS, "");
    return s.length >= 4 ? s : w.slice(0, 4);
  };
  const STOP = new Set("был была были было меня мне мой моя его ему ее она они он мы вы ты я на в во с со к ко по за из от до у о об при для не ни то это как что чтобы который которая которые его их или либо и а но же ли бы да нет человек человека гражданин гражданина кто тип типа короче просто когда если там тут".split(" "));
  const words = (s) => norm(s).split(/\s+/).filter((w) => w.length > 1 && !STOP.has(w));

  // разговорное → слова из законов (основы)
  const SYN = [
    [["напал", "нападен", "наезд", "кинулс", "бросилс", "атак"], ["посягательств", "насили", "нападен", "разбо", "побо"]],
    [["ударил", "избил", "бил", "драк", "подрал", "пиздил", "отпиздил", "морд", "кулак"], ["побо", "вред", "здоров", "хулиганств", "насили"]],
    [["убил", "убийств", "завалил", "грохнул", "замочил", "добил", "добив"], ["убийств", "смерт"]],
    [["стрелял", "стрельб", "выстрел", "пальб", "шмалял", "ствол", "пушк", "огнестрел"], ["оруж", "посягательств", "обнажен", "оборот"]],
    [["нож", "холодн", "пырнул", "порезал"], ["оруж", "холодн", "вред", "посягательств"]],
    [["украл", "кража", "спиздил", "стырил", "вынес", "обокрал"], ["краж", "хищен", "грабеж"]],
    [["ограбил", "отжал", "отобрал", "грабеж"], ["грабеж", "разбо", "хищен"]],
    [["угнал", "угон", "тачк", "машин", "авто"], ["угон", "транспорт", "завладен", "автомобил"]],
    [["нарко", "трав", "косяк", "порош", "закладк", "барыг"], ["наркотическ", "сбыт"]],
    [["пьян", "бух", "выпил", "алко", "пиво", "водк"], ["алкогол", "опьянен", "распит"]],
    [["маск", "лицо", "шлем", "балаклав"], ["личност", "скрыва", "маск", "неприемлем"]],
    [["голый", "голая", "раздет", "торс", "без майки"], ["неприемлем", "оголен", "одежд"]],
    [["оскорбил", "обозвал", "послал", "мат", "нахамил", "унизил"], ["оскорблен", "хулиганств", "клевет"]],
    [["врал", "оклеветал", "клевет", "слух"], ["клевет"]],
    [["не подчинил", "не слушал", "игнор", "неповин", "убежал", "сбежал", "скрылс"], ["неповиновен", "требовани", "уклонен", "побег"]],
    [["помешал", "мешал", "вмешал", "лез"], ["вмешательств", "задержани", "помех"]],
    [["скорост", "гнал", "превысил", "быстро"], ["скоростн", "скорост", "лимит"]],
    [["телефон", "мобил"], ["телефон"]],
    [["подрезал", "дрифт", "опасн езд", "безрассуд"], ["безрассудн", "вождени"]],
    [["авари", "дтп", "врезал", "сбил"], ["авари", "дтп", "столкновен"]],
    [["номер", "без номер", "регистрац", "птс"], ["номер", "регистрац", "птс"]],
    [["взятк", "подкуп", "откат"], ["взятк", "коммерческ"]],
    [["угроз", "угрожал", "пригрозил"], ["угроз"]],
    [["дом", "квартир", "влез", "проник"], ["жилищ", "проникновен", "неприкосновен"]],
    [["курил", "сигарет", "кальян"], ["курен"]],
    [["сломал", "разбил", "испортил", "поджог", "сжег"], ["порч", "повреждени", "уничтожен"]],
    [["коп", "мент", "полиц", "сотрудник", "шериф", "офицер"], ["сотрудник", "правоохранительн"]],
    [["шокер", "дубинк", "бронежилет", "броник"], ["спецсредств", "государственн"]],
    [["похитил", "похищ", "заложник", "держал"], ["похищен", "заложник", "свобод"]],
    [["документ", "паспорт", "права", "лиценз"], ["лиценз", "документ", "удостоверен"]]
  ];
  const SYN_N = SYN.map(([from, to]) => [from.map(norm), to]);

  function expand(query) {
    const q = norm(query);
    const extra = [];
    SYN_N.forEach(([from, to]) => { if (from.some((f) => q.includes(f.trim()))) extra.push(...to); });
    return { stems: words(q).map(stem), extra };
  }

  // индекс: основы слов каждой статьи (заголовок весит больше)
  let index = null;
  function build(arts) {
    index = arts.map((a) => ({
      a,
      title: new Set(words((a.short || "") + " " + a.title).map(stem)),
      body: norm([a.full, a.note, a.pen].join(" ")),
      num: norm(a.key)
    }));
  }

  // возвращает статьи по убыванию совпадения
  window.smartSearch = function (arts, query) {
    if (!index || index.length !== arts.length) build(arts);
    const q = norm(query).trim();
    if (!q) return arts;
    // поиск по номеру: «17.1», «ст 22»
    const num = q.match(/\d+(?:\.\d+)*/);
    const { stems, extra } = expand(q);
    const scored = index.map((it) => {
      let score = 0;
      if (num && (it.num === num[0] || it.num.startsWith(num[0] + " "))) score += 50;
      stems.forEach((s) => {
        if (/^\d/.test(s)) return;
        if ([...it.title].some((t) => t.startsWith(s) || (t.length >= 4 && s.startsWith(t)))) score += 8;
        else if (s.length >= 4 && it.body.includes(s)) score += 3;
      });
      extra.forEach((e) => {
        if ([...it.title].some((t) => t.startsWith(e) || (t.length >= 5 && e.startsWith(t)))) score += 4;
        else if (it.body.includes(e)) score += 1;
      });
      return { a: it.a, score };
    });
    return scored.filter((x) => x.score > 0).sort((x, y) => y.score - x.score).map((x) => x.a);
  };
})();
